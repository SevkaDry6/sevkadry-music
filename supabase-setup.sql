-- SEVKADRY MUSIC: отдельная таблица музыкального каталога.
-- Перед запуском замени admin@example.com на email своего администратора.
create table if not exists public.music_tracks (
  id bigint generated by default as identity primary key,
  title text not null,
  mood text not null default '',
  cover_url text,
  audio_url text not null,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.music_tracks enable row level security;

-- Все посетители могут читать только опубликованные треки.
drop policy if exists "Public can read published music" on public.music_tracks;
create policy "Public can read published music"
on public.music_tracks for select
to anon, authenticated
using (published = true);

-- Только администратор с указанным email может добавлять треки.
drop policy if exists "Only music admin can insert" on public.music_tracks;
create policy "Only music admin can insert"
on public.music_tracks for insert
to authenticated
with check ((auth.jwt() ->> 'email') = 'admin@example.com');

-- Только администратор может изменять треки.
drop policy if exists "Only music admin can update" on public.music_tracks;
create policy "Only music admin can update"
on public.music_tracks for update
to authenticated
using ((auth.jwt() ->> 'email') = 'admin@example.com')
with check ((auth.jwt() ->> 'email') = 'admin@example.com');

-- Только администратор может удалять треки.
drop policy if exists "Only music admin can delete" on public.music_tracks;
create policy "Only music admin can delete"
on public.music_tracks for delete
to authenticated
using ((auth.jwt() ->> 'email') = 'admin@example.com');
